import { createReadStream, statSync } from "node:fs";
import { createServer } from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";

// <lang><zh-CN>server root 固定到 ignored W-P104 evidence，不接受任意 filesystem root。</zh-CN><en>The server root is fixed to ignored W-P104 evidence and never accepts an arbitrary filesystem root.</en></lang>
const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
// <lang><zh-CN>只允许 loopback port 配置；默认端口与其它本地 evidence server 分离。</zh-CN><en>Only the loopback port is configurable; the default stays separate from other local evidence servers.</en></lang>
const port = Number.parseInt(process.env.HIA_WP104_PORT ?? "43104", 10);
// <lang><zh-CN>静态根必须由 evidence preparer 先生成。</zh-CN><en>The static root must be generated by the evidence preparer first.</en></lang>
const siteRoot = path.join(repositoryRoot, "dist", "wp104-portal-theme-interaction");

/**
 * @lang zh-CN 按扩展名返回浏览器可用的最小 MIME 类型。
 * @lang en Returns the minimal browser-compatible MIME type for an extension.
 *
 * @param {string} filePath 已验证的 evidence file path。Validated evidence file path.
 * @returns {string} HTTP Content-Type。HTTP Content-Type.
 */
function resolveContentType(filePath) {
  const extension = path.extname(filePath).toLowerCase();
  return ({
    ".css": "text/css; charset=utf-8",
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".md": "text/markdown; charset=utf-8"
  })[extension] ?? "application/octet-stream";
}

/**
 * @lang zh-CN 把 URL pathname 解析为固定 evidence root 内的文件，拒绝 traversal 与目录列表。
 * @lang en Resolves a URL pathname to a file under the fixed evidence root, rejecting traversal and directory listings.
 *
 * @param {string} pathname URL pathname。URL pathname.
 * @returns {string | undefined} 安全文件路径，拒绝时为 undefined。Safe file path, or undefined when refused.
 */
function resolveEvidenceFile(pathname) {
  // <lang><zh-CN>decode 失败由 caller 转为 404，不能导致 server 崩溃。</zh-CN><en>Decode failures become 404 responses at the caller and cannot crash the server.</en></lang>
  const decodedPath = decodeURIComponent(pathname);
  // <lang><zh-CN>目录请求只映射 index.html，不提供 filesystem listing。</zh-CN><en>Directory requests map only to index.html and never expose filesystem listings.</en></lang>
  const relativePath = decodedPath.endsWith("/") ? `${decodedPath}index.html` : decodedPath;
  const candidate = path.resolve(siteRoot, `.${relativePath}`);
  if (!candidate.startsWith(`${path.resolve(siteRoot)}${path.sep}`)) {
    return undefined;
  }
  try {
    return statSync(candidate).isFile() ? candidate : undefined;
  } catch {
    return undefined;
  }
}

// <lang><zh-CN>loopback-only server 不执行脚本、代理网络或写 filesystem。</zh-CN><en>The loopback-only server executes no scripts, proxies no network, and writes no filesystem state.</en></lang>
const server = createServer((request, response) => {
  try {
    const requestUrl = new URL(request.url ?? "/", `http://127.0.0.1:${port}`);
    if (requestUrl.pathname === "/favicon.ico") {
      response.writeHead(204);
      response.end();
      return;
    }
    const filePath = resolveEvidenceFile(requestUrl.pathname);
    if (!filePath) {
      response.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
      response.end("Not found");
      return;
    }
    response.writeHead(200, {
      "Content-Type": resolveContentType(filePath),
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff"
    });
    createReadStream(filePath).pipe(response);
  } catch {
    response.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
    response.end("Not found");
  }
});

server.listen(port, "127.0.0.1", () => {
  console.log(`W-P104 evidence server ready on http://127.0.0.1:${port}/`);
});

