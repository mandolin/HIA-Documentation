import { createReadStream, statSync } from "node:fs";
import { createServer } from "node:http";
import path from "node:path";
import { fileURLToPath } from "node:url";

// <lang><zh-CN>server root 固定为 W-P117 ignored browser site，不接受 caller filesystem root。</zh-CN><en>The server root is fixed to the ignored W-P117 browser site and accepts no caller filesystem root.</en></lang>
const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const siteRoot = path.join(repositoryRoot, "dist", "wp117-portal-presentation-adoption", "site");
// <lang><zh-CN>只允许通过环境变量选择 loopback 端口；默认值与其它 evidence server 分离。</zh-CN><en>Only the loopback port is selectable through an environment variable; the default is isolated from other evidence servers.</en></lang>
const port = Number.parseInt(process.env.HIA_WP117_PORT ?? "43117", 10);

/** @lang zh-CN 返回浏览器验收所需的最小 MIME allowlist。 @lang en Returns the minimal MIME allowlist required by browser acceptance. */
function resolveContentType(filePath) {
  const extension = path.extname(filePath).toLowerCase();
  return ({
    ".css": "text/css; charset=utf-8",
    ".html": "text/html; charset=utf-8",
    ".js": "text/javascript; charset=utf-8",
    ".json": "application/json; charset=utf-8",
    ".txt": "text/plain; charset=utf-8"
  })[extension] ?? "application/octet-stream";
}

/**
 * @lang zh-CN 把 URL pathname 约束到固定站点根，拒绝 traversal 和目录枚举。
 * @lang en Constrains a URL pathname to the fixed site root, rejecting traversal and directory listing.
 *
 * @param {string} pathname 请求 pathname。Request pathname.
 * @returns {string | undefined} 已验证文件，拒绝时为 undefined。Validated file, or undefined when refused.
 */
function resolveSiteFile(pathname) {
  const decodedPath = decodeURIComponent(pathname);
  const relativePath = decodedPath.endsWith("/") ? `${decodedPath}index.html` : decodedPath;
  const candidate = path.resolve(siteRoot, `.${relativePath}`);
  if (!candidate.startsWith(`${path.resolve(siteRoot)}${path.sep}`)) {
    return undefined;
  }
  try {
    return statSync(candidate).isFile() ? candidate : undefined;
  } catch {
    return undefined;
  }
}

// <lang><zh-CN>loopback server 只读 committed-code 生成的 ignored fixture，不代理网络、不执行源码、不写文件。</zh-CN><en>The loopback server only reads an ignored fixture generated by committed code; it proxies no network, executes no source, and writes no file.</en></lang>
const server = createServer((request, response) => {
  try {
    const requestUrl = new URL(request.url ?? "/", `http://127.0.0.1:${port}`);
    if (requestUrl.pathname === "/favicon.ico") {
      response.writeHead(204);
      response.end();
      return;
    }
    const filePath = resolveSiteFile(requestUrl.pathname);
    if (!filePath) {
      response.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
      response.end("Not found");
      return;
    }
    response.writeHead(200, {
      "Content-Type": resolveContentType(filePath),
      "Cache-Control": "no-store",
      "X-Content-Type-Options": "nosniff"
    });
    createReadStream(filePath).pipe(response);
  } catch {
    response.writeHead(404, { "Content-Type": "text/plain; charset=utf-8" });
    response.end("Not found");
  }
});

server.listen(port, "127.0.0.1", () => {
  console.log(`W-P117 evidence server ready on http://127.0.0.1:${port}/`);
});
